"""On-chain reads for HouseExchange + guarded executors (local anvil / Mezo testnet only).

Selectors come from forge (`keeper/abi/*.selectors.json`, regenerated by scripts/export-abi.sh).
"""

from __future__ import annotations

import json
import os
import subprocess
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Optional
from urllib.parse import urlparse

from .rpc import JsonRpc, RpcError, to_signed, words

ROOT = Path(__file__).resolve().parents[2]
MEZO_TESTNET_CHAIN_ID = 31611
TESTNET_HOSTS = {"rpc.test.mezo.org"}
LOCAL_HOSTS = {"127.0.0.1", "localhost", "::1"}


def load_selectors(name: str = "HouseExchange") -> dict[str, str]:
    raw = json.loads((ROOT / "keeper/abi" / f"{name}.selectors.json").read_text())
    return {sig: "0x" + sel for sig, sel in raw.items()}


def enc_uint(*vals: int) -> str:
    return "".join(f"{v:064x}" for v in vals)


def dyn_uint_array(raw: bytes) -> list[int]:
    w = words(raw)
    off = w[0] // 32
    n = w[off]
    return w[off + 1 : off + 1 + n]


@dataclass
class Order:
    id: int
    trader: str
    kind: int  # 0 open, 1 close
    status: int  # 1 pending
    is_long: bool
    created_at: int
    margin: int
    size: int
    position_id: int


@dataclass
class Snapshot:
    block_ts: int
    price: Optional[int]
    price_updated_at: int
    price_error: Optional[str]
    house_cash: int
    queue_total: int
    house_equity: int
    long_oi: int
    short_oi: int
    open_ids: list[int]
    order_count: int


class ExchangeReader:
    def __init__(self, rpc: JsonRpc, exchange: str, selectors: Optional[dict[str, str]] = None):
        self.rpc = rpc
        self.ex = exchange
        self.sel = selectors or load_selectors()

    def _call(self, sig: str, *args: int) -> bytes:
        return self.rpc.eth_call(self.ex, self.sel[sig] + enc_uint(*args))

    def _u(self, sig: str, *args: int) -> int:
        return words(self._call(sig, *args))[0]

    def current_price(self) -> tuple[int, int]:
        w = words(self._call("currentPrice()"))
        return w[0], w[1]

    def order(self, oid: int) -> Order:
        w = words(self._call("getOrder(uint256)", oid))
        return Order(oid, "0x" + f"{w[0]:064x}"[-40:], w[1], w[2], bool(w[3]), w[4], w[5], w[6], w[7])

    def pending_orders(self, start: int, end: int) -> list[int]:
        return dyn_uint_array(self._call("pendingOrderIds(uint256,uint256)", start, end))

    def is_liquidatable(self, pid: int) -> bool:
        return bool(self._u("isLiquidatable(uint256)", pid))

    def bust_price(self, pid: int) -> int:
        return self._u("bustPriceOf(uint256)", pid)

    def snapshot(self) -> Snapshot:
        price, upd, err = None, 0, None
        try:
            price, upd = self.current_price()
        except RpcError as e:  # stale oracle / Pyth deviation
            err = str(e)
        return Snapshot(
            block_ts=self.rpc.block_timestamp(),
            price=price,
            price_updated_at=upd,
            price_error=err,
            house_cash=self._u("houseCash()"),
            queue_total=self._u("queueTotal()"),
            house_equity=to_signed(self._u("houseEquity()")),
            long_oi=self._u("longOi()"),
            short_oi=self._u("shortOi()"),
            open_ids=dyn_uint_array(self._call("openPositionIds()")),
            order_count=self._u("orderCount()"),
        )


class ExecutionRefused(RuntimeError):
    pass


class LocalExecutor:
    """Sends txs ONLY to a local anvil node from an unlocked anvil account (no key is ever read).

    Refuses unless: RPC host is local, node answers anvil_nodeInfo, chainId == 31611, sender is unlocked.
    """

    def __init__(self, rpc: JsonRpc, exchange: str, sender: str, selectors: Optional[dict[str, str]] = None):
        self.rpc, self.ex, self.sender = rpc, exchange, sender
        self.sel = selectors or load_selectors()

    def check(self) -> None:
        host = urlparse(self.rpc.url).hostname or ""
        if host not in LOCAL_HOSTS:
            raise ExecutionRefused(f"refusing to send: RPC host '{host}' is not local")
        try:
            self.rpc.call("anvil_nodeInfo")
        except Exception as e:  # noqa: BLE001
            raise ExecutionRefused(f"refusing to send: endpoint is not anvil ({e})") from e
        if self.rpc.chain_id() != MEZO_TESTNET_CHAIN_ID:
            raise ExecutionRefused("refusing to send: chainId is not 31611 fork")
        if self.sender.lower() not in [a.lower() for a in self.rpc.call("eth_accounts")]:
            raise ExecutionRefused("refusing to send: sender is not an unlocked anvil account")

    def send(self, to: str, data: str) -> str:
        self.check()
        tx = self.rpc.call("eth_sendTransaction", [{"from": self.sender, "to": to, "data": data, "gas": hex(3_000_000)}])
        for _ in range(50):
            rc = self.rpc.call("eth_getTransactionReceipt", [tx])
            if rc is not None:
                if int(rc["status"], 16) != 1:
                    raise RpcError(f"tx reverted: {tx}")
                return tx
            time.sleep(0.2)
        raise RpcError(f"no receipt: {tx}")

    def execute(self, oid: int) -> str:
        return self.send(self.ex, self.sel["executeOrder(uint256)"] + enc_uint(oid))

    def liquidate(self, pid: int) -> str:
        return self.send(self.ex, self.sel["liquidate(uint256)"] + enc_uint(pid))

    def harvest(self, n: int) -> str:
        return self.send(self.ex, self.sel["harvest(uint256)"] + enc_uint(n))


class TestnetExecutor:
    """Mezo TESTNET only. Signs via `forge script script/KeeperOps.s.sol`, which reads MEZO_TESTNET_PRIVATE_KEY
    from the inherited environment. The key never appears in argv, logs or files.
    """

    def __init__(self, rpc: JsonRpc, exchange: str):
        self.rpc, self.ex = rpc, exchange

    def check(self) -> None:
        host = urlparse(self.rpc.url).hostname or ""
        if host not in TESTNET_HOSTS:
            raise ExecutionRefused(f"refusing: '{host}' is not the Mezo testnet RPC")
        if self.rpc.chain_id() != MEZO_TESTNET_CHAIN_ID:
            raise ExecutionRefused("refusing: chainId is not 31611")
        if not os.environ.get("MEZO_TESTNET_PRIVATE_KEY"):
            raise ExecutionRefused("refusing: MEZO_TESTNET_PRIVATE_KEY not set")

    def _run(self, sig: str, *args: str) -> str:
        self.check()
        cmd = ["forge", "script", "script/KeeperOps.s.sol", "--sig", sig, *args, "--rpc-url", self.rpc.url,
               "--broadcast", "--slow", "-q"]
        r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, timeout=180)
        if r.returncode != 0:
            raise RpcError(f"forge script failed: {sig} {args} :: {r.stderr.strip()[-300:]}")
        return "forge-script-ok"

    def execute(self, oid: int) -> str:
        return self._run("execute(address,uint256)", self.ex, str(oid))

    def liquidate(self, pid: int) -> str:
        return self._run("liquidate(address,uint256)", self.ex, str(pid))

    def harvest(self, n: int) -> str:
        return self._run("harvest(address,uint256)", self.ex, str(n))
